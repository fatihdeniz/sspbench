#!/usr/bin/env python3
"""
Convert Novelty Engine output to aiXamine benchmark format.

This script converts questions generated by the novelty engine into the format
required by the aiXamine testing pipeline, similar to nqopen.jsonl format.

Usage:
    python convert_to_benchmark_format.py --input data/novelty/theme_iter_*.KI_questions.json --output benchmarks/my_benchmark.jsonl
    python convert_to_benchmark_format.py --theme "science" --iterations 3 --output benchmarks/science_benchmark.jsonl
"""

import argparse
import json
import os
import sys
from pathlib import Path
import glob
import re

# Get project root (parent of scripts/)
script_dir = Path(__file__).resolve().parent
project_root = script_dir.parent


def normalize_answer(answer):
    """Normalize answer string for comparison."""
    if not answer:
        return ""
    
    # Convert to string if not already
    answer = str(answer).strip()
    
    # Basic normalization
    answer = answer.lower()
    
    # Remove common punctuation at the end
    answer = answer.rstrip('.,;:!?')
    
    return answer


def generate_answer_aliases(answer):
    """Generate common variations of the answer."""
    if not answer:
        return []
    
    aliases = set()
    
    # Base answer
    normalized = normalize_answer(answer)
    aliases.add(normalized)
    
    # Without "the" prefix
    if normalized.startswith("the "):
        aliases.add(normalized[4:])
    
    # Handle common date formats
    if re.match(r'\d{4}', answer):  # Year
        aliases.add(answer.strip())
    
    # Handle numeric answers with/without commas
    if any(c.isdigit() for c in answer):
        # With commas
        aliases.add(answer.replace(',', ''))
        # Without commas
        if ',' in answer:
            aliases.add(answer.replace(',', ''))
    
    return list(aliases)


def load_questions_from_iterations(theme, engine='novelty', max_iterations=None):
    """Load questions from multiple iteration files."""
    data_dir = project_root / 'data' / engine
    all_questions = []
    
    # Pattern for iteration files
    theme_slug = theme.replace(' ', '_')
    pattern = f"{theme_slug}_iter_*.KI_questions.json"
    
    files = sorted(data_dir.glob(pattern))
    
    if not files:
        print(f"Warning: No question files found matching pattern: {data_dir / pattern}")
        return []
    
    for file_path in files:
        # Extract iteration number from filename
        match = re.search(r'iter_(\d+)', file_path.name)
        iter_num = int(match.group(1)) if match else None
        
        # Skip if beyond max_iterations
        if max_iterations and iter_num and iter_num > max_iterations:
            continue
        
        with open(file_path, 'r') as f:
            questions = json.load(f)
            
            # Add iteration number if not present
            for q in questions:
                if 'iteration' not in q and iter_num:
                    q['iteration'] = iter_num
            
            all_questions.extend(questions)
            print(f"Loaded {len(questions)} questions from {file_path.name}")
    
    return all_questions


def load_questions_from_files(input_paths):
    """Load questions from one or more JSON files."""
    all_questions = []
    
    for pattern in input_paths:
        # Expand glob pattern
        files = glob.glob(pattern)
        
        if not files:
            print(f"Warning: No files found matching pattern: {pattern}")
            continue
        
        for file_path in files:
            with open(file_path, 'r') as f:
                questions = json.load(f)
                all_questions.extend(questions)
                print(f"Loaded {len(questions)} questions from {file_path}")
    
    return all_questions


def convert_to_benchmark_format(questions, benchmark_name="novelty_benchmark"):
    """
    Convert questions to aiXamine benchmark format.
    
    Format:
        - question_id: Unique ID (e.g., "novelty_0")
        - question: The question text
        - target: The primary answer
        - target_aliases: List of acceptable answer variations (lowercased)
        - target_type: String representation of target_aliases
        - question_source: Source (e.g., "wikipedia")
        - question_source_domain: Domain/category
        - wiki_title: Wikipedia title if available
    """
    converted = []
    
    for idx, q in enumerate(questions):
        # Generate unique ID
        question_id = f"{benchmark_name}_{idx}"
        
        # Extract fields
        question_text = q.get('question', '')
        answer = q.get('gold_answer', q.get('answer', ''))
        
        if not question_text or not answer:
            print(f"Warning: Skipping question {idx} - missing question or answer")
            continue
        
        # Generate answer aliases
        target_aliases = generate_answer_aliases(answer)
        
        # Build converted entry
        entry = {
            'question_id': question_id,
            'question': question_text,
            'target': str(answer).strip(),
            'target_aliases': target_aliases,
            'target_type': ", ".join(target_aliases),
            'question_source': 'wikipedia',
            'question_source_domain': q.get('category', q.get('parent_category', 'unknown')),
            'wiki_title': q.get('wiki_entity', '')
        }
        
        # Add optional metadata as extra fields (not part of standard format)
        if 'iteration' in q:
            entry['metadata_iteration'] = q['iteration']
        if 'faithfulness' in q:
            entry['metadata_faithfulness'] = q['faithfulness']
        if 'quality' in q and isinstance(q['quality'], dict):
            entry['metadata_quality_score'] = q['quality'].get('total_score')
            entry['metadata_quality_suitable'] = q['quality'].get('is_suitable')
        if 'wiki_url' in q:
            entry['metadata_wiki_url'] = q['wiki_url']
        
        converted.append(entry)
    
    return converted


def save_benchmark(data, output_path):
    """Save benchmark data to JSONL file."""
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    
    with open(output_path, 'w') as f:
        for entry in data:
            json.dump(entry, f)
            f.write('\n')
    
    print(f"\n✓ Saved {len(data)} questions to: {output_path}")


def print_summary(data):
    """Print summary statistics of the benchmark."""
    print("\n" + "="*80)
    print("BENCHMARK SUMMARY")
    print("="*80)
    print(f"Total questions: {len(data)}")
    
    # Category distribution
    categories = {}
    for entry in data:
        cat = entry.get('question_source_domain', 'unknown')
        categories[cat] = categories.get(cat, 0) + 1
    
    print(f"\nCategories: {len(categories)}")
    top_categories = sorted(categories.items(), key=lambda x: x[1], reverse=True)[:10]
    for cat, count in top_categories:
        print(f"  - {cat}: {count}")
    if len(categories) > 10:
        print(f"  ... and {len(categories) - 10} more")
    
    # Iteration distribution (if available)
    iterations = {}
    for entry in data:
        if 'metadata_iteration' in entry:
            iter_num = entry['metadata_iteration']
            iterations[iter_num] = iterations.get(iter_num, 0) + 1
    
    if iterations:
        print(f"\nIterations:")
        for iter_num in sorted(iterations.keys()):
            print(f"  - Iteration {iter_num}: {iterations[iter_num]} questions")
    
    # Quality metrics (if available)
    quality_scores = [e.get('metadata_quality_score') for e in data if 'metadata_quality_score' in e]
    if quality_scores:
        avg_quality = sum(quality_scores) / len(quality_scores)
        suitable = sum(1 for e in data if e.get('metadata_quality_suitable'))
        print(f"\nQuality metrics:")
        print(f"  - Average quality score: {avg_quality:.2f}/10")
        print(f"  - Suitable questions: {suitable}/{len(quality_scores)} ({100*suitable/len(quality_scores):.1f}%)")
    
    # Sample questions
    print(f"\nSample questions:")
    for i, entry in enumerate(data[:3], 1):
        print(f"\n{i}. {entry['question']}")
        print(f"   Answer: {entry['target']}")
        print(f"   Aliases: {', '.join(entry['target_aliases'][:3])}")
        if 'metadata_quality_score' in entry:
            print(f"   Quality: {entry['metadata_quality_score']}/10")


def parse_args():
    """Parse command line arguments."""
    parser = argparse.ArgumentParser(
        description='Convert Novelty Engine output to aiXamine benchmark format',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Load from theme iterations
  python convert_to_benchmark_format.py --theme "science" --iterations 3 \\
      --output benchmarks/science_benchmark.jsonl
  
  # Load from specific files
  python convert_to_benchmark_format.py \\
      --input "data/novelty/*_iter_*.KI_questions.json" \\
      --output benchmarks/all_questions.jsonl
  
  # Specify benchmark name for question IDs
  python convert_to_benchmark_format.py --theme "history" \\
      --benchmark-name "history_bench" \\
      --output benchmarks/history.jsonl
        """
    )
    
    # Input options
    input_group = parser.add_mutually_exclusive_group(required=True)
    input_group.add_argument('--input', nargs='+', help='Input JSON file(s) with questions (supports glob patterns)')
    input_group.add_argument('--theme', help='Theme name to load from data/<engine>/')
    
    parser.add_argument('--engine', default='novelty', help='Engine name (default: novelty)')
    parser.add_argument('--iterations', type=int, help='Maximum number of iterations to include (when using --theme)')
    
    # Output options
    parser.add_argument('--output', '-o', required=True, help='Output JSONL file path')
    parser.add_argument('--benchmark-name', default='novelty_benchmark', 
                       help='Benchmark name for question IDs (default: novelty_benchmark)')
    
    # Options
    parser.add_argument('--no-summary', action='store_true', help='Skip printing summary')
    
    return parser.parse_args()


def main():
    """Main execution function."""
    args = parse_args()
    
    # Load questions
    if args.theme:
        print(f"Loading questions for theme: {args.theme}")
        questions = load_questions_from_iterations(
            args.theme, 
            engine=args.engine,
            max_iterations=args.iterations
        )
    else:
        print(f"Loading questions from files: {args.input}")
        questions = load_questions_from_files(args.input)
    
    if not questions:
        print("Error: No questions loaded")
        return 1
    
    print(f"\nTotal questions loaded: {len(questions)}")
    
    # Convert to benchmark format
    print("\nConverting to benchmark format...")
    benchmark_data = convert_to_benchmark_format(questions, args.benchmark_name)
    
    if not benchmark_data:
        print("Error: No valid questions after conversion")
        return 1
    
    # Save benchmark
    save_benchmark(benchmark_data, args.output)
    
    # Print summary
    if not args.no_summary:
        print_summary(benchmark_data)
    
    print("\n" + "="*80)
    print("✓ CONVERSION COMPLETED SUCCESSFULLY")
    print("="*80)
    print(f"\nBenchmark file ready for testing: {args.output}")
    print(f"Use this file with your aiXamine testing scripts.")
    
    return 0


if __name__ == "__main__":
    sys.exit(main())
